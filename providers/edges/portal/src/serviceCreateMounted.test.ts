// @vitest-environment happy-dom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createApp, nextTick } from 'vue'
const api = vi.hoisted(() => ({ fetchServiceCatalog: vi.fn(), listEdges: vi.fn(), createKubeEdgeService: vi.fn(), getService: vi.fn(), isContextChangedError: (error: unknown) => (error as { reason?: string })?.reason === 'ContextChanged' }))
vi.mock('./api', () => api)
vi.mock('./portalkit/toast', () => ({ toast: vi.fn() }))
import ServiceCreate from './ServiceCreate.vue'
async function flush() { await Promise.resolve(); await nextTick(); await Promise.resolve(); await nextTick() }
function deferred() {
  let reject!: (error: unknown) => void
  const promise = new Promise<void>((_, rejectPromise) => { reject = rejectPromise })
  return { promise, reject }
}
describe('service create duplicate recovery', () => {
  let host: HTMLDivElement
  let app: ReturnType<typeof createApp>
  beforeEach(() => {
    const values = new Map<string, string>()
    vi.stubGlobal('localStorage', { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => values.set(key, value), removeItem: (key: string) => values.delete(key), clear: () => values.clear(), key: (index: number) => [...values.keys()][index] ?? null, get length() { return values.size } })
    vi.resetAllMocks()
    api.fetchServiceCatalog.mockResolvedValue([])
    api.listEdges.mockResolvedValue([{ name: 'edge-a', type: 'server', connected: true }])
    host = document.createElement('div')
    document.body.appendChild(host)
  })
  afterEach(() => { app?.unmount(); host.remove(); localStorage.clear(); vi.useRealTimers(); vi.restoreAllMocks() })
  async function mountForm() {
    app = createApp(ServiceCreate)
    app.mount(host)
    await flush()
    const name = host.querySelector<HTMLInputElement>('input[placeholder="home-assistant"]')!
    name.value = 'living-room'
    name.dispatchEvent(new Event('input', { bubbles: true }))
    await nextTick()
    return name
  }
  it('preserves the draft, associates the error, and focuses the name when focus stays on submit', async () => {
    const pending = deferred()
    api.createKubeEdgeService.mockReturnValue(pending.promise)
    const name = await mountForm()
    const submit = host.querySelector<HTMLButtonElement>('button[type="submit"]')!
    submit.focus()
    submit.click()
    await nextTick()
    expect(submit.getAttribute('aria-disabled')).toBe('true')
    submit.click()
    expect(api.createKubeEdgeService).toHaveBeenCalledTimes(1)
    pending.reject({ reason: 'AlreadyExists' })
    await flush()
    expect(name.value).toBe('living-room')
    expect(name.getAttribute('aria-invalid')).toBe('true')
    expect(host.querySelector('#service-create-name-error')?.textContent).toContain('already exists')
    expect(document.activeElement).toBe(name)
    name.dispatchEvent(new Event('input', { bubbles: true }))
    await nextTick()
    expect(name.hasAttribute('aria-invalid')).toBe(false)
  })
  it('does not attach a delayed duplicate error to an edited name or steal focus', async () => {
    const pending = deferred()
    api.createKubeEdgeService.mockReturnValue(pending.promise)
    const name = await mountForm()
    host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    name.value = 'new-name'
    name.dispatchEvent(new Event('input', { bubbles: true }))
    name.focus()
    pending.reject({ reason: 'AlreadyExists' })
    await flush()
    expect(name.value).toBe('new-name')
    expect(name.hasAttribute('aria-invalid')).toBe(false)
    expect(host.querySelector('.banner.error')?.textContent).toContain('living-room')
    expect(document.activeElement).toBe(name)
  })
  it('does not move focus when the user moved to another control', async () => {
    const pending = deferred()
    api.createKubeEdgeService.mockReturnValue(pending.promise)
    const name = await mountForm()
    host.querySelector<HTMLButtonElement>('button[type="submit"]')!.focus()
    host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    const other = host.querySelector<HTMLSelectElement>('select')!
    other.focus()
    pending.reject({ reason: 'AlreadyExists' })
    await flush()
    expect(name.getAttribute('aria-invalid')).toBe('true')
    expect(document.activeElement).toBe(other)
  })
  it('ignores a response after the form unmounts', async () => {
    const pending = deferred()
    api.createKubeEdgeService.mockReturnValue(pending.promise)
    await mountForm()
    host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    app.unmount()
    pending.reject({ reason: 'AlreadyExists' })
    await flush()
    expect(host.querySelector('[role="alert"]')).toBeNull()
  })
  it('locks the submitted fields and checks an uncertain outcome without retrying', async () => {
    const pending = deferred()
    api.createKubeEdgeService.mockReturnValue(pending.promise)
    api.getService.mockResolvedValue({ name: 'living-room' })
    const name = await mountForm()
    host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    await nextTick()
    expect(name.closest('fieldset')?.disabled).toBe(true)
    pending.reject({ reason: 'ServiceCreateUnknown' })
    await flush()
    expect(name.closest('fieldset')?.disabled).toBe(true)
    expect(host.textContent).toContain('Could not confirm whether service “living-room”')
    host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    expect(api.createKubeEdgeService).toHaveBeenCalledTimes(1)
    const check = [...host.querySelectorAll('button')].find(button => button.textContent?.includes('Check service'))!
    check.click()
    await flush()
    expect(api.getService).toHaveBeenCalledWith('living-room', expect.any(AbortSignal))
    expect(host.textContent).toContain('does not establish which request created it')
  })
  it('warns that a missing service may still be processing', async () => {
    api.createKubeEdgeService.mockRejectedValue({ reason: 'ServiceCreateUnknown' })
    api.getService.mockRejectedValue({ reason: 'NotFound' })
    await mountForm()
    host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    await flush()
    ;[...host.querySelectorAll('button')].find(button => button.textContent?.includes('Check service'))!.click()
    await flush()
    expect(host.textContent).toContain('original request may still be processing')
  })
  it('times out a stalled create and check without accepting late results', async () => {
    let resolveCreate!: () => void
    let resolveCheck!: (value: unknown) => void
    api.createKubeEdgeService.mockReturnValue(new Promise<void>(resolve => { resolveCreate = resolve }))
    api.getService.mockReturnValue(new Promise(resolve => { resolveCheck = resolve }))
    await mountForm()
    vi.useFakeTimers()
    host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    await vi.advanceTimersByTimeAsync(15000)
    await flush()
    expect(host.textContent).toContain('Could not confirm whether service “living-room”')
    expect(api.createKubeEdgeService.mock.calls[0][1].aborted).toBe(true)
    resolveCreate()
    await flush()
    expect(host.textContent).toContain('Could not confirm whether service “living-room”')
    ;[...host.querySelectorAll('button')].find(button => button.textContent?.includes('Check service'))!.click()
    await vi.advanceTimersByTimeAsync(15000)
    await flush()
    expect(host.textContent).toContain('service check timed out')
    expect(api.getService.mock.calls[0][1].aborted).toBe(true)
    resolveCheck({ name: 'living-room' })
    await flush()
    expect(host.textContent).not.toContain('is present')
  })
  it('does not report a service as found when the lookup response is invalid', async () => {
    api.createKubeEdgeService.mockRejectedValue({ reason: 'ServiceCreateUnknown' })
    api.getService.mockRejectedValue({ reason: 'ProtocolError', message: 'Service response did not identify the requested service' })
    await mountForm()
    host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    await flush()
    ;[...host.querySelectorAll('button')].find(button => button.textContent?.includes('Check service'))!.click()
    await flush()
    expect(host.textContent).toContain('Could not check the service')
    expect(host.textContent).not.toContain('is present')
  })
  it('blocks an unreadable record only in its workspace and user scope', async () => {
    localStorage.setItem(`railgrid:edges:service-create-attempt:${JSON.stringify(['workspace', 'user'])}`, '{')
    app = createApp(ServiceCreate, { cluster: 'workspace', userKey: 'other' })
    app.mount(host)
    await flush()
    expect(host.textContent).not.toContain('record could not be read')
    app.unmount()
    app = createApp(ServiceCreate, { cluster: 'workspace', userKey: 'user' })
    app.mount(host)
    await flush()
    expect(host.textContent).toContain('record could not be read')
    expect(host.querySelector('fieldset')?.disabled).toBe(true)
    ;[...host.querySelectorAll('button')].find(button => button.textContent?.includes('Clear unreadable'))!.click()
    await flush()
    expect(localStorage.length).toBe(0)
  })
  it('blocks creation if recovery storage fails', async () => {
    vi.spyOn(localStorage, 'setItem').mockImplementation(() => { throw new Error('unavailable') })
    api.createKubeEdgeService.mockRejectedValue({ reason: 'ServiceCreateUnknown' })
    app = createApp(ServiceCreate, { cluster: 'workspace', userKey: 'user' })
    app.mount(host)
    await flush()
    const name = host.querySelector<HTMLInputElement>('input[placeholder="home-assistant"]')!
    name.value = 'living-room'
    name.dispatchEvent(new Event('input', { bubbles: true }))
    await nextTick()
    host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    await flush()
    expect(host.textContent).toContain('Could not save service creation recovery state')
    expect(api.createKubeEdgeService).not.toHaveBeenCalled()
  })
  it('restores each legacy and unique record and preserves replacements', async () => {
    const base = `railgrid:edges:service-create-attempt:${JSON.stringify(['workspace', 'user'])}`
    const legacy = JSON.stringify({ name: 'legacy', id: 'old' })
    localStorage.setItem(base, legacy)
    localStorage.setItem(`${base}:new`, JSON.stringify({ name: 'new', id: 'new' }))
    api.getService.mockRejectedValue({ reason: 'NotFound' })
    app = createApp(ServiceCreate, { cluster: 'workspace', userKey: 'user' })
    app.mount(host)
    await flush()
    expect(host.textContent).toContain('service “legacy”')
    ;[...host.querySelectorAll('button')].find(b => b.textContent?.includes('Check service'))!.click()
    await flush()
    localStorage.setItem(base, JSON.stringify({ name: 'replacement', id: 'replacement' }))
    ;[...host.querySelectorAll('button')].find(b => b.textContent?.includes('Allow another request'))!.click()
    await flush()
    expect(host.textContent).toContain('Could not clear service creation recovery state')
    expect(localStorage.length).toBe(2)
    localStorage.setItem(base, legacy)
    ;[...host.querySelectorAll('button')].find(b => b.textContent?.includes('Allow another request'))!.click()
    await flush()
    expect(host.textContent).toContain('service “new”')
    expect(localStorage.length).toBe(1)
  })
  it('blocks creation when recovery enumeration fails', async () => {
    vi.spyOn(localStorage, 'key').mockImplementation(() => { throw new Error('unavailable') })
    localStorage.setItem('unrelated', 'value')
    app = createApp(ServiceCreate, { cluster: 'workspace', userKey: 'user' })
    app.mount(host)
    await flush()
    expect(host.textContent).toContain('Could not check service creation recovery records')
    expect(host.querySelector('fieldset')?.disabled).toBe(true)
    expect(api.createKubeEdgeService).not.toHaveBeenCalled()
  })

  it('retains another tab’s overlapping attempt when this request finishes', async () => {
    const base = `railgrid:edges:service-create-attempt:${JSON.stringify(['workspace', 'user'])}`
    const pending = deferred()
    api.createKubeEdgeService.mockReturnValue(pending.promise)
    app = createApp(ServiceCreate, { cluster: 'workspace', userKey: 'user' })
    app.mount(host)
    await flush()
    const name = host.querySelector<HTMLInputElement>('input[placeholder="home-assistant"]')!
    name.value = 'living-room'
    name.dispatchEvent(new Event('input', { bubbles: true }))
    await nextTick()
    host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    expect(localStorage.length).toBe(1)
    localStorage.setItem(`${base}:other`, JSON.stringify({ name: 'other', id: 'other' }))
    pending.reject({ reason: 'AlreadyExists' })
    await flush()
    expect(localStorage.length).toBe(1)
    expect(localStorage.getItem(`${base}:other`)).toContain('other')
    app.unmount()
    app = createApp(ServiceCreate, { cluster: 'workspace', userKey: 'user' })
    app.mount(host)
    await flush()
    expect(host.textContent).toContain('service “other”')
  })

  it('requires a fresh completed inspection before clearing a record', async () => {
    const base = `railgrid:edges:service-create-attempt:${JSON.stringify(['workspace', 'user'])}`
    localStorage.setItem(`${base}:a`, JSON.stringify({ name: 'same', id: 'a' }))
    localStorage.setItem(`${base}:b`, JSON.stringify({ name: 'same', id: 'b' }))
    api.getService.mockRejectedValueOnce({ reason: 'NotFound' })
    app = createApp(ServiceCreate, { cluster: 'workspace', userKey: 'user' })
    app.mount(host)
    await flush()
    ;[...host.querySelectorAll('button')].find(b => b.textContent?.includes('Check service'))!.click()
    await flush()
    const pending = deferred()
    api.getService.mockReturnValueOnce(pending.promise)
    ;[...host.querySelectorAll('button')].find(b => b.textContent?.includes('Check service'))!.click()
    await flush()
    expect([...host.querySelectorAll('button')].some(b => b.textContent?.includes('Allow another request'))).toBe(false)
    expect(localStorage.length).toBe(2)
    pending.reject({ reason: 'NotFound' })
    await flush()
    ;[...host.querySelectorAll('button')].find(b => b.textContent?.includes('Allow another request'))!.click()
    await flush()
    expect(localStorage.length).toBe(1)
    expect([...host.querySelectorAll('button')].some(b => b.textContent?.includes('Allow another request'))).toBe(false)
  })
  it.each(['confirmed', 'rejected'] as const)('reports the known %s outcome if record cleanup fails', async outcome => {
    const pending = deferred()
    let resolve!: () => void
    api.createKubeEdgeService.mockReturnValue(outcome === 'confirmed' ? new Promise<void>(r => { resolve = r }) : pending.promise)
    app = createApp(ServiceCreate, { cluster: 'workspace', userKey: 'user' })
    app.mount(host)
    await flush()
    const name = host.querySelector<HTMLInputElement>('input[placeholder="home-assistant"]')!
    name.value = 'living-room'
    name.dispatchEvent(new Event('input', { bubbles: true }))
    await nextTick()
    host.querySelector('form')!.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    vi.spyOn(localStorage, 'removeItem').mockImplementation(() => { throw new Error('unavailable') })
    if (outcome === 'confirmed') resolve()
    else pending.reject({ reason: 'AlreadyExists' })
    await flush()
    expect(host.textContent).toContain(outcome === 'confirmed' ? 'was created' : 'was rejected')
    expect(host.textContent).not.toContain('Could not confirm whether service')
  })

})
